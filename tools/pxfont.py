GW, GH = 5, 7


def text_width(text, scale=2, gap=1):
    n = max(1, len(text))
    return n * (GW + gap) * scale - gap * scale


def text_height(scale=2):
    return GH * scale


def draw(img, xy, text, scale=2, level=255, gap=1, anchor="la"):
    """Paste `text` as blocks of `scale` px. anchor: l/c/r + a/c/b."""
    w = text_width(text, scale, gap)
    h = text_height(scale)
    x, y = xy
    if anchor[0] == "c":
        x -= w // 2
    elif anchor[0] == "r":
        x -= w
    if anchor[1] == "c":
        y -= h // 2
    elif anchor[1] == "b":
        y -= h

    layer = Image.new("L", (w, h), 0)
    px = layer.load()
    for gi, ch in enumerate(text.upper()):
        rows = GLYPHS.get(ch, GLYPHS[" "]).split()
        for ry, row in enumerate(rows):
            for cx, on in enumerate(row):
                if on != "1":
                    continue
                for dy in range(scale):
                    for dx in range(scale):
                        X = (gi * (GW + gap) + cx) * scale + dx
                        Y = ry * scale + dy
                        if 0 <= X < w and 0 <= Y < h:
                            px[X, Y] = 255
    img.paste(level, (int(x), int(y)), layer)
    return w, h
